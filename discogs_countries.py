def _key(name) -> str:
    text = unicodedata.normalize('NFKD', str(name or ''))
    text = ''.join(c for c in text if not unicodedata.combining(c)).casefold()
    return re.sub(r'[^a-z0-9]+', ' ', text).strip()


def country_code(name) -> str:
    """'Italy' -> 'IT', 'UK' -> 'GB', 'Europe' -> 'XE'. A value that already is a code is
    returned as it is. Names with no single code ('UK & Europe') give ''."""
    raw = str(name or '').strip()
    key = _key(raw)
    if not key:
        return ''
    found = _DISCOGS_COUNTRY_ALIASES.get(key) or _ISO_COUNTRY_NAMES.get(key)
    if found:
        return found
    if re.fullmatch(r'[A-Z]{2}', raw) and raw in _KNOWN_CODES:
        return raw                                   # already a code ("IT")
    return ''


_KNOWN_CODES = frozenset(_ISO_COUNTRY_NAMES.values()) | frozenset(_DISCOGS_COUNTRY_ALIASES.values())
